"""Сколько места у текста на самом деле. Шаг 3 плана `PLAN-4.2` (`ADR-0015`).

Бокс — это замысел дизайнера, а не предел. PowerPoint нигде не обрезает текст по
боксу: не влезший просто рисуется дальше. Значит «текст выше бокса» — лишь
признак того, что текст **вылез**, а брак это или нет, решает, **есть ли куда
вылезать**.

## Откуда правила

Замерено на корпусе из одиннадцати шаблонов
(`WORKLOG/2026-09-13-autofit.md`), сверено с растром.

**Помеха — любая фигура, не только текстовая.** Текст есть у 143 фигур корпуса
из 2209; помехой чаще оказывается иконка или плашка.

**Подложка — граница по своему дальнему краю, и это исправлено 19 сентября**
(`Z-38`). Здесь стояло: «подложка границей не является, отдельного правила не
требует, её отсеивает та же проверка расстояния». Утверждение верно для
**верхнего** края подложки и неверно для нижнего: текст, выросший ниже дна
карточки, из неё выходит, и зритель это видит, а мерка говорила «влезает».

Замер: VK Tech, слайд 5, текст кончается на 4.10 дюйма, карточка — на 4.02,
до следующей карточки 0.36 дюйма. Детектор докладывал «переполнено 2 → 0, всё
влезло», и проверенный файл не отличался от непроверенного
(`WORKLOG/2026-09-19-z38-baseline.md`).

Прежний мутационный прогон не ошибался: он проверял **другое правило** —
«подложку отбросить», то есть снять ограничение. Нужно было обратное —
ограничение добавить. Мёртвым было исключение, а не граница.

**Невидимые фигуры пропускаются.** Клон несёт мусор донора: скрытые фигуры и
заготовки за холстом. Скрытая фигура не мешает зрителю, а место занимала бы.

**Край слайда — такая же граница, как соседняя фигура.**

**Направление задаёт вертикальный якорь.** Верхний — текст растёт вниз, нижний —
вверх, остальные (центр, по ширине, распределён) — в обе стороны.

## Свойство, на которое опиралась безопасность правки, и чем оно стало

**Было:** доступное место всегда не меньше полезной высоты бокса, значит мерка
может дефекты только снимать, но не добавлять, и ложных срабатываний не
прибавится по построению.

**С 19 сентября это неверно, и обходить это молчанием нельзя.** Граница по низу
подложки может оказаться **выше** низа бокса, и тогда доступного места меньше,
чем полезной высоты. Мерка теперь умеет дефекты и добавлять.

Чем это оплачено вместо прежней гарантии:

- **замером цены.** По корпусу 71 фигура получила более тесную границу, и
  дефектами стали **четыре**; на трёх вариантах VK Tech — по три. Не лавина;
- **проверкой глазами.** Все помеченные случаи открыты растром и оказались
  настоящими: заголовок карточки в две строки налезает на текст под ним;
- **порогом перекрытия.** Подложкой считается только фигура, покрывающая бокс
  по ширине не меньше чем на `_BACKING_COVERAGE`. Иначе узкая иконка, задевшая
  бокс краем, обрезала бы место по своему низу.
"""

from __future__ import annotations

from .metrics import Box, Measurement, ShapeMetric

#: msoAnchor: текст прижат к верху — растёт вниз.
ANCHOR_TOP = 1
#: Текст прижат к низу — растёт вверх.
ANCHOR_BOTTOM = 3

#: Допуск на округление координат в пунктах. Зонд округляет до сотых.
SLACK = 0.5


def _box_of(metric: ShapeMetric) -> Box:
    return Box(
        slide=metric.slide, shape_id=metric.shape_id,
        x=metric.left, y=metric.top, w=metric.width, h=metric.height,
    )


def _blockers(box: Box, boxes: tuple[Box, ...]) -> list[Box]:
    """Фигуры, способные помешать этому тексту.

    Отсеиваются: он сам, невидимые и всё, что не пересекается с ним по
    горизонтали — текст растёт вертикально, вбок не заглядывать.

    **Подложка отдельного правила не требует.** Фигура, содержащая наш бокс,
    начинается выше его нижнего края и кончается ниже верхнего, а такие отсеет
    проверка расстояния в `free_below`/`free_above`. План закладывал здесь
    отдельное условие; мутационный прогон показал, что оно мёртвое, а замер по
    корпусу подтвердил: 16 дефектов с ним и 16 без, списки совпали.
    """
    out = []
    for other in boxes:
        if other.slide != box.slide or other.shape_id == box.shape_id:
            continue
        if not other.visible:
            continue
        if other.right <= box.x + SLACK or other.x >= box.right - SLACK:
            continue
        out.append(other)
    return out


#: Какую долю ширины бокса помеха должна перекрывать, чтобы считаться
#: подложкой, а не соседом. Узкая иконка, задевшая бокс краем, подложкой не
#: является, и обрезать по её низу было бы ложным дефектом
#: (`PLAN-6.1`, логическая проверка 1, дыра 1).
_BACKING_COVERAGE = 0.8


def backings(box: Box, blockers: list[Box]) -> list[Box]:
    """Подложки: фигуры, внутри которых бокс лежит, а не рядом с которыми.

    Признак — верх помехи не ниже верха бокса, низ не выше верха бокса, и по
    горизонтали она покрывает бокс почти целиком.
    """
    out = []
    for other in blockers:
        if other.y > box.y + SLACK or other.bottom < box.y - SLACK:
            continue
        overlap = min(other.right, box.right) - max(other.x, box.x)
        if box.w > 0 and overlap / box.w < _BACKING_COVERAGE:
            continue
        out.append(other)
    return out


def free_below(box: Box, blockers: list[Box], page_height: float) -> float:
    """Пустое место под фигурой до ближайшей помехи или низа слайда."""
    gap = page_height - box.bottom
    for other in blockers:
        distance = other.y - box.bottom
        if distance >= -SLACK:
            gap = min(gap, max(0.0, distance))
    # Низ подложки — тоже граница, и это `Z-38`.
    #
    # Раньше подложка отбрасывалась целиком: она начинается выше нижнего края
    # бокса, значит «стоит за текстом, а не под ним». Верно для её ВЕРХНЕГО
    # края и неверно для нижнего. Текст, выросший ниже дна подложки, из неё
    # выходит, и зритель это видит.
    #
    # Замер 19 сентября, VK Tech, слайд 5: текст кончается на 4.10 дюйма,
    # карточка — на 4.02, а детектор рапортовал «всё влезло», потому что до
    # следующей карточки оставалось 0.36 дюйма
    # (`WORKLOG/2026-09-19-z38-baseline.md`).
    for back in backings(box, blockers):
        gap = min(gap, max(0.0, back.bottom - box.bottom))
    return max(0.0, gap)


def free_above(box: Box, blockers: list[Box]) -> float:
    """Пустое место над фигурой до ближайшей помехи или верха слайда."""
    gap = box.y
    for other in blockers:
        distance = box.y - other.bottom
        if distance >= -SLACK:
            gap = min(gap, max(0.0, distance))
    # Зеркально `free_below`: для текста, растущего вверх, границей служит
    # верхний край подложки (`Z-38`).
    for back in _backings_above(box, blockers):
        gap = min(gap, max(0.0, box.y - back.y))
    return max(0.0, gap)


def _backings_above(box: Box, blockers: list[Box]) -> list[Box]:
    """Подложки для текста, растущего вверх: помеха охватывает низ бокса."""
    out = []
    for other in blockers:
        if other.bottom < box.bottom - SLACK or other.y > box.bottom + SLACK:
            continue
        overlap = min(other.right, box.right) - max(other.x, box.x)
        if box.w > 0 and overlap / box.w < _BACKING_COVERAGE:
            continue
        out.append(other)
    return out


def available_height(metric: ShapeMetric, measurement: Measurement) -> float:
    """Высота, на которую текст этой фигуры может рассчитывать.

    Без боксов или без габаритов слайда возвращается полезная высота бокса —
    ровно прежнее поведение. Это сознательный откат, а не тихое снятие
    дефектов: не зная окружения, мы не вправе объявлять место свободным
    (`PLAN-4.2`, первая логическая проверка, дыра 4).
    """
    if not measurement.boxes or measurement.page is None:
        return metric.usable_height

    box = _box_of(metric)
    blockers = _blockers(box, measurement.boxes)
    page_height = measurement.page[1]

    if metric.anchor == ANCHOR_TOP:
        extra = free_below(box, blockers, page_height)
    elif metric.anchor == ANCHOR_BOTTOM:
        extra = free_above(box, blockers)
    else:
        # Центр, «по ширине», «распределён»: текст расходится в обе стороны.
        extra = free_above(box, blockers) + free_below(box, blockers, page_height)

    return metric.usable_height + max(0.0, extra)


def height_ratio(metric: ShapeMetric, measurement: Measurement) -> float:
    """Во сколько раз текст выше доступного места. <= 1 — зритель брака не видит."""
    return metric.text_height / max(available_height(metric, measurement), 1.0)

#: Какую долю набранного текста непрозрачная фигура должна накрыть, чтобы это
#: считалось заслонением (`Z-47`, `PLAN-7.7`).
#:
#: Порог выбран **растром, а не кривой**. Число заметно зависит от него — 5%
#: даёт 11 случаев по корпусу, 10% даёт 8, — и соблазн взять «поустойчивее»
#: был. Проверено глазами на самом слабом случае, `stilnyj` слайд 2 при **7%**:
#: бегущая фигурка закрывает «шабло[н]» и «[ч]асами». Дефект настоящий и
#: виден, а порог 10% выбросил бы три таких **молча**
#: (`WORKLOG/2026-09-20-z47-baseline.md`).
OCCLUSION_SHARE = 0.05

#: Ниже этой непрозрачности фигура ничего не заслоняет. Замер поймал ровно
#: такой ложный случай: текст, накрытый сверху на 100%, читался отлично.
OPAQUE = 0.5


def occluders(text_rect: tuple[float, float, float, float], box: Box,
              boxes: tuple[Box, ...], texts: frozenset[tuple[int, str]]) -> float:
    """Какую долю набранного текста накрывает непрозрачная фигура **поверх** него.

    Три условия, и каждое стоило отдельного опровержения замером:

    * **поверх.** Без порядка отрисовки перекрытие не значит ничего: карточка
      накрывает свой же текст на 100%, и это норма. Она лежит ниже;
    * **непрозрачная.** Прозрачная рамка накрывает текст целиком и не мешает
      ему совсем — такой случай нашёлся и был отвергнут;
    * **не текст.** Чужой текст рядом — это не заслонение, а соседство, и
      разбирается оно переполнением.

    Меряется по **набранному** тексту, а не по боксу: бокс бывает вчетверо
    больше своей надписи, и заслонение его пустой части никого не волнует.
    """
    tx, ty, tw, th = text_rect
    if tw <= 0 or th <= 0:
        return 0.0
    worst = 0.0
    for other in boxes:
        if other.slide != box.slide or other.shape_id == box.shape_id:
            continue
        if not other.visible or other.opacity < OPAQUE:
            continue
        if (other.slide, other.shape_id) in texts:
            continue
        if other.z <= box.z:
            continue
        wide = min(tx + tw, other.right) - max(tx, other.x)
        high = min(ty + th, other.bottom) - max(ty, other.y)
        if wide <= 0 or high <= 0:
            continue
        worst = max(worst, (wide * high) / (tw * th))
    return worst
